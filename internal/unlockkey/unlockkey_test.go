// The golden vectors both languages read. The TypeScript side
// (web/src/lib/unlockkey, FE-153) reads the same file.
var vectorsPath = filepath.Join("..", "..", "testdata", "unlockkey", "vectors.json")

// -update rewrites vectors.json from vectorInputs. Run it only when the
// format changes on purpose: a new format is a new version, never an edit
// to v1's vectors.
var update = flag.Bool("update", false, "rewrite testdata/unlockkey/vectors.json")

type vectorFile struct {
	Comment    string   `json:"comment"`
	Format     string   `json:"format"`
	HKDFHash   string   `json:"hkdf_hash"`
	HKDFSalt   string   `json:"hkdf_salt_hex"`
	InfoPrefix string   `json:"info_prefix"`
	Vectors    []vector `json:"vectors"`
}

type vector struct {
	Name      string `json:"name"`
	PRF       string `json:"prf_hex"`
	Purpose   string `json:"purpose"`
	Scalar    string `json:"scalar_hex"`
	Identity  string `json:"identity"`
	Recipient string `json:"recipient"`
}

func seq(start byte) []byte {
	b := make([]byte, PRFSize)
	for i := range b {
		b[i] = start + byte(i)
	}
	return b
}

func fill(v byte) []byte { return bytes.Repeat([]byte{v}, PRFSize) }

func hashed(s string) []byte { h := sha256.Sum256([]byte(s)); return h[:] }

// vectorInputs are the edge cases the vectors pin: the all-zero and all-one
// PRF outputs, the same PRF output under both purposes (they must differ),
// a counting sequence, and two outputs with no structure.
var vectorInputs = []struct {
	name    string
	prf     []byte
	purpose Purpose
}{
	{"all-zero custody", fill(0x00), PurposeCustody},
	{"all-zero backup", fill(0x00), PurposeBackup},
	{"all-ff custody", fill(0xff), PurposeCustody},
	{"all-ff backup", fill(0xff), PurposeBackup},
	{"sequence 00..1f custody", seq(0x00), PurposeCustody},
	{"sequence e0..ff backup", seq(0xe0), PurposeBackup},
	{"unstructured A custody", hashed("innsegl unlock vector A"), PurposeCustody},
	{"unstructured B backup", hashed("innsegl unlock vector B"), PurposeBackup},
}

func buildVectors(t *testing.T) vectorFile {
	t.Helper()
	f := vectorFile{
		Comment:    "Golden vectors for the unlock-key derivation (internal/unlockkey, web/src/lib/unlockkey). Generated by `go test ./internal/unlockkey -run TestBAK038 -update`. Frozen: a change here is a new format version.",
		Format:     FormatVersion,
		HKDFHash:   "SHA-256",
		HKDFSalt:   "",
		InfoPrefix: InfoPrefix,
	}
	for _, in := range vectorInputs {
		id, err := Derive(in.prf, in.purpose)
		if err != nil {
			t.Fatalf("%s: Derive: %v", in.name, err)
		}
		scalar, err := deriveScalar(in.prf, in.purpose)
		if err != nil {
			t.Fatalf("%s: deriveScalar: %v", in.name, err)
		}
		f.Vectors = append(f.Vectors, vector{
			Name:      in.name,
			PRF:       hex.EncodeToString(in.prf),
			Purpose:   string(in.purpose),
			Scalar:    hex.EncodeToString(scalar),
			Identity:  id.String(),
			Recipient: id.Recipient().String(),
		})
	}
	return f
}

// BAK-038: PRF output → AGE-SECRET-KEY-1… / age1…, Go side, against the
// golden vectors the TypeScript side also reads.
func TestBAK038GoldenVectors(t *testing.T) {
	if *update {
		b, err := json.MarshalIndent(buildVectors(t), "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsPath, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	raw, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("read vectors: %v", err)
	}
	var f vectorFile
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatalf("parse vectors: %v", err)
	}
	if f.Format != FormatVersion || f.InfoPrefix != InfoPrefix || f.HKDFHash != "SHA-256" || f.HKDFSalt != "" {
		t.Fatalf("vector file header = %q %q %q %q, want the v1 constants", f.Format, f.InfoPrefix, f.HKDFHash, f.HKDFSalt)
	}
	if len(f.Vectors) < 5 {
		t.Fatalf("%d vectors, want at least 5", len(f.Vectors))
	}
	for _, v := range f.Vectors {
		prf, err := hex.DecodeString(v.PRF)
		if err != nil {
			t.Fatalf("%s: prf_hex: %v", v.Name, err)
		}
		scalar, err := deriveScalar(prf, Purpose(v.Purpose))
		if err != nil {
			t.Fatalf("%s: deriveScalar: %v", v.Name, err)
		}
		if got := hex.EncodeToString(scalar); got != v.Scalar {
			t.Errorf("%s: scalar = %s, want %s", v.Name, got, v.Scalar)
		}
		id, err := Derive(prf, Purpose(v.Purpose))
		if err != nil {
			t.Fatalf("%s: Derive: %v", v.Name, err)
		}
		if id.String() != v.Identity {
			t.Errorf("%s: identity does not match the vector", v.Name)
		}
		if got := id.Recipient().String(); got != v.Recipient {
			t.Errorf("%s: recipient = %s, want %s", v.Name, got, v.Recipient)
		}
	}
}

// BAK-038: the vectors on disk are exactly what the code generates from
// vectorInputs, so a vector cannot be edited by hand to match a bug.
func TestBAK038VectorsAreGenerated(t *testing.T) {
	raw, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("read vectors: %v", err)
	}
	want, err := json.MarshalIndent(buildVectors(t), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(raw, append(want, '\n')) {
		t.Fatal("vectors.json differs from what the derivation generates")
	}
}

// BAK-038: the derived identity is a real age identity: age parses it back,
// and a file encrypted to its recipient opens with it.
func TestBAK038IdentityIsAgeX25519(t *testing.T) {
	id, err := Derive(hashed("round trip"), PurposeCustody)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(id.String(), "AGE-SECRET-KEY-1") || !strings.HasPrefix(id.Recipient().String(), "age1") {
		t.Fatalf("identity/recipient prefixes wrong: %s", id.Recipient())
	}
	parsed, err := age.ParseX25519Identity(id.String())
	if err != nil {
		t.Fatalf("age cannot parse the identity: %v", err)
	}
	var buf bytes.Buffer
	w, err := age.Encrypt(&buf, id.Recipient())
	if err != nil {
		t.Fatal(err)
	}
	if _, err = io.WriteString(w, "material"); err != nil {
		t.Fatal(err)
	}
	if err = w.Close(); err != nil {
		t.Fatal(err)
	}
	r, err := age.Decrypt(&buf, parsed)
	if err != nil {
		t.Fatalf("decrypt with the derived identity: %v", err)
	}
	got, err := io.ReadAll(r)
	if err != nil || string(got) != "material" {
		t.Fatalf("round trip = %q, %v", got, err)
	}
}

// BAK-038: the two purposes give unrelated keys from one PRF output, and the
// derivation is deterministic.
func TestBAK038PurposesSeparateAndDeterministic(t *testing.T) {
	prf := hashed("purposes")
	a, err := Derive(prf, PurposeCustody)
	if err != nil {
		t.Fatal(err)
	}
	b, err := Derive(prf, PurposeBackup)
	if err != nil {
		t.Fatal(err)
	}
	if a.String() == b.String() {
		t.Fatal("custody and backup derived the same identity")
	}
	again, err := Derive(prf, PurposeCustody)
	if err != nil {
		t.Fatal(err)
	}
	if again.String() != a.String() {
		t.Fatal("Derive is not deterministic")
	}
}

// BAK-038: anything but a 32-byte PRF output and a known purpose is refused.
func TestBAK038RefusesBadInput(t *testing.T) {
	for _, n := range []int{0, 16, 31, 33, 64} {
		if _, err := Derive(make([]byte, n), PurposeCustody); !errors.Is(err, ErrPRFLength) {
			t.Errorf("Derive(%d bytes) = %v, want ErrPRFLength", n, err)
		}
	}
	if _, err := Derive(nil, PurposeCustody); !errors.Is(err, ErrPRFLength) {
		t.Errorf("Derive(nil) = %v, want ErrPRFLength", err)
	}
	for _, p := range []Purpose{"", "Custody", "custody ", "signing"} {
		if _, err := Derive(fill(1), p); !errors.Is(err, ErrPurpose) {
			t.Errorf("Derive(purpose %q) = %v, want ErrPurpose", p, err)
		}
	}
}

// bech32 against BIP-173's own valid test strings, lower-cased hrp.
func TestBech32EncodeKnownVectors(t *testing.T) {
	for _, tc := range []struct {
		hrp  string
		data []byte
		want string
	}{
		{"a", nil, "a12uel5l"},
		{"abcdef", []byte{0x00, 0x44, 0x32, 0x14, 0xc7, 0x42, 0x54, 0xb6, 0x35, 0xcf, 0x84, 0x65, 0x3a, 0x56, 0xd7, 0xc6, 0x75, 0xbe, 0x77, 0xdf}, "abcdef1qpzry9x8gf2tvdw0s3jn54khce6mua7lmqqqxw"},
	} {
		if got := bech32Encode(tc.hrp, tc.data); got != tc.want {
			t.Errorf("bech32Encode(%q) = %s, want %s", tc.hrp, got, tc.want)
		}
	}
}
